import { z } from "zod";
import { fail, ok, parseBody, route } from "@/lib/api";
import { prisma } from "@/lib/prisma";
import { clientIp, rateLimit } from "@/lib/rate-limit";
import { RATE_LIMITS } from "@/lib/constants";
import { decodeSlug, menuOwnerId } from "@/lib/menu";

export const runtime = "nodejs";

/**
 * Telemetry for suggestions on the public menu.
 *
 * Unauthenticated by design — the reporter is a guest with no identity — which
 * makes every field here untrusted and shapes the whole handler:
 *
 *   * The venue comes from the **slug**, resolved server-side, and the edge is
 *     confirmed against that venue's own recommendations. A caller therefore
 *     cannot write events onto another restaurant's numbers, which is the only
 *     way this endpoint could damage anything.
 *   * Writes are idempotent on `(sessionKey, source, recommended, type)`, so a
 *     refresh, a remount, a retry or a double tap all collapse into the one
 *     event that happened.
 *   * Rate limited per IP like the order and staff-call endpoints.
 *
 * Purchases are deliberately not reportable here; those are written by
 * `createOrder` from facts the server already holds.
 */
const EventSchema = z.object({
  slug: z.string().min(1),
  sourceProductId: z.string().min(1).max(40),
  recommendedProductId: z.string().min(1).max(40),
  type: z.enum(["IMPRESSION", "INTERACTION", "ADD_TO_CART"]),
  /** Opaque per-guest-session id generated by the browser. */
  sessionKey: z.string().min(8).max(64),
});

export const POST = route(async (request: Request) => {
  const limit = await rateLimit(
    `rec-event:${clientIp(request)}`,
    RATE_LIMITS.recommendationEvent,
  );
  if (!limit.allowed) return fail(429, "Too many requests", "RATE_LIMITED");

  const input = await parseBody(request, EventSchema);

  const venue = await prisma.restaurant.findUnique({
    where: { slug: decodeSlug(input.slug) },
    select: { id: true, parentRestaurantId: true, isActive: true },
  });

  // Same shape of refusal for a missing venue and a switched-off one, so
  // probing this endpoint reveals nothing about which slugs exist.
  if (!venue || !venue.isActive) return ok({ recorded: false });

  /*
    Events belong to the venue that owns the *menu*.

    A branch serves the chain's dishes, and the suggestion being measured is the
    chain's. Filing the event under the branch would scatter one menu's
    performance across every site that serves it — the same reasoning that puts
    pricing and discount codes on the menu owner.
  */
  const ownerId = menuOwnerId(venue);

  /*
    The edge must exist and be switched on, scoped to that venue.

    This is what stops the endpoint from being a way to write arbitrary rows: a
    pair the owner never configured is not recorded at all.
  */
  const edge = await prisma.productRecommendation.findFirst({
    where: {
      restaurantId: ownerId,
      isActive: true,
      sourceProductId: input.sourceProductId,
      recommendedProductId: input.recommendedProductId,
    },
    select: { id: true },
  });

  if (!edge) return ok({ recorded: false });

  /*
    `createMany` with `skipDuplicates` rather than an upsert.

    The unique index is the deduplication, and a repeat is not an error worth
    reporting to a menu — it is the normal consequence of a guest refreshing.
    This turns the second and every later attempt into a no-op write.
  */
  const result = await prisma.recommendationEvent.createMany({
    data: [
      {
        restaurantId: ownerId,
        sourceProductId: input.sourceProductId,
        recommendedProductId: input.recommendedProductId,
        type: input.type,
        sessionKey: input.sessionKey,
      },
    ],
    skipDuplicates: true,
  });

  return ok({ recorded: result.count > 0 });
});
